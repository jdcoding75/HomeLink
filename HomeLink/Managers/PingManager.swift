    // ── Offline catch queue — thoughts that arrived while we were away ──
    //
    // Realtime and pushes both miss when the app is offline; the pings are
    // safe in Supabase. On every foreground/reconnect we sweep for unread
    // ones we've never SEEN: the newest becomes the catch, the rest stay in
    // History (they're already there server-side). No error states — quiet
    // either way.

    /// Ping ids that ever entered the local queue — so offline sweeps never
    /// re-trigger a catch for something already offered. Capped at 50. [3/6]
    private var seenPingIDs: [String] {
        get { UserDefaults.standard.stringArray(forKey: "seenPingIDs") ?? [] }
        set { UserDefaults.standard.set(Array(newValue.suffix(50)), forKey: "seenPingIDs") }
    }

    private func rememberSeen(_ id: UUID?) {
        guard let id else { return }
        var seen = seenPingIDs
        guard !seen.contains(id.uuidString) else { return }
        seen.append(id.uuidString)
        seenPingIDs = seen
    }

    /// Sweep one partner's pings for unread thoughts that never reached
    /// this device. `resolveName` maps the partner id to their card name.
    func syncMissedThoughts(partnerID: UUID, partnerName: String) async {
        let records = await SupabaseService.shared.fetchPings(with: partnerID)
        let me = SupabaseService.localUserID
        let seen = Set(seenPingIDs)
        // Unread, addressed to me, never seen here — oldest…newest
        let missed = records
            .filter { record in
                record.openedAt == nil
                    && record.toUser.uuidString == me?.uuidString
                    && !seen.contains(record.id.uuidString)
            }
            .sorted { $0.createdAt < $1.createdAt }
        guard !missed.isEmpty else { return }
        log.info("offline-sync: \(missed.count) missed thought(s) from \(partnerName, privacy: .public)")

        // All are remembered as seen; only the NEWEST goes through the
        // queue → catch. Older ones rest in History (already server-side).
        for record in missed { rememberSeen(record.id) }
        if let newest = missed.last {
            receivePing(fromName: partnerName, emoji: newest.emoji,
                        remoteID: newest.id, senderStyle: newest.senderStyle,
                        message: newest.message, tagline: newest.tagline)
        }
    }

    func sendPing(to person: Person, emoji: String) async {
        isSending = true
        defer { isSending = false }
        let pairedID = person.pairedUserID ?? "local-stub"
        // The real Supabase insert (SupabaseService.sendPing) carries
        // sender_style = SenderStyle.effectiveForCurrentUser; this legacy
        // mock path stays style-less.
        try? await networkService.sendPing(toPairedUserID: pairedID, emoji: emoji)
        HapticEngine.pingSent()
    }

    /// THE real send. Fires the Supabase insert (with its own retry layer)
    /// and — critically — surfaces failure instead of swallowing it: the
    /// flight animation plays optimistically, but if the insert never lands
    /// the user is told their thought did not travel.
    func sendRemote(to userID: UUID, emoji: String, style: SenderStyle,
                    message: String? = nil, tagline: String? = nil) {
        log.info("sendRemote: → \(userID.uuidString, privacy: .public) emoji=\(emoji, privacy: .public) style=\(style.rawValue, privacy: .public) msg=\(message != nil, privacy: .public) tag=\(tagline != nil, privacy: .public)")
        Task {
            do {
                try await SupabaseService.shared.sendPing(to: userID, emoji: emoji, style: style, message: message, tagline: tagline)
                log.info("sendRemote: delivered ✓")
            } catch {
                log.error("sendRemote: FAILED — \(error.localizedDescription, privacy: .public)")
                sendFailedNotice = "couldn't send — check your connection"
                try? await Task.sleep(nanoseconds: 4_000_000_000)
                sendFailedNotice = nil
            }
        }
    }

    // ════════════════════════════════════════════════════════════════════
    // [phase2 stage A] LINK-BASED SEND — LIVE (un-gated; PATH-2 "a link for everyone")
    // ════════════════════════════════════════════════════════════════════
    // The Build-3 `#if DEBUG` guardrail ("/m/ links aren't openable until Build 4")
    // is obsolete — links open since 4a, the web page is live, and the legacy
    // sendRemote double-send is removed. This is now the live release send path.
    // It NEVER auto-shares (the user picks the destination in the share sheet).

    /// "couldn't create your link — retry" — the message insert failed. The
    /// animation already played (sacred); this is a quiet, non-blocking notice
    /// with a retry that re-runs the insert.
    @Published var linkFailedNotice: String?
    private var lastLinkSend: (() -> Void)?

    // [#1 share-on-animation-complete] The share sheet must appear only AFTER the send
    // animation finishes — not the instant the insert returns (which lands mid-flight,
    // cutting the animation off). createAndShareLink stashes the built share text here
    // instead of presenting; the View calls markSendAnimationComplete() from finishSend
    // (every send-out animation's terminal funnel). Whichever lands second presents.
    private var pendingShareText: String?
    private var sendAnimationComplete = false

    /// Store the just-sent thought as a `messages` row, then present the share
    /// sheet with the /m/[id] link + the short-code fallback. Background work —
    /// the caller has already kicked off the (uninterrupted) send animation.
    /// `onStored` fires with the new message id once the insert succeeds — the
    /// caller records the (S1) SentLink (messageID → local contact) so Stage B/C
    /// can stamp the right contact. (PingManager has no ModelContext by design;
    /// the SwiftData write lives in PeopleManager.)
    func createAndShareLink(content: String?, emoji: String, instrument: String,
                            senderName: String, shortCode: String,
                            personID: UUID? = nil,
                            onStored: ((UUID) -> Void)? = nil) {
        let run: () -> Void = { [weak self] in
            guard let self else { return }
            self.linkFailedNotice = nil
            // [#1] New send → clear any prior link-ready / animation-done coordination so
            // THIS send's sheet waits for THIS send's animation to finish (runs
            // synchronously, before the animation can complete).
            self.pendingShareText = nil
            self.sendAnimationComplete = false
            Task { @MainActor in
                do {
                    let id = try await SupabaseService.shared.insertMessage(
                        content: content, emoji: emoji, instrument: instrument,
                        senderDisplayName: senderName.isEmpty ? nil : senderName)
                    // (S1) record the sent-link → contact mapping (if a contact was attached).
                    if personID != nil { onStored?(id) }
                    let link = MessageLink.url(for: id)
                    let text = MessageLink.shareText(senderName: senderName,
                                                     link: link, shortCode: shortCode)
                    self.log.info("link: message stored (id=\(id.uuidString, privacy: .public)) — sharing once the send animation completes")
                    // [#1] Stash the built link; present only once the send animation has
                    // finished (markSendAnimationComplete). Whichever lands second wins.
                    self.pendingShareText = text
                    self.presentShareIfReady()
                } catch {
                    self.log.error("link: insert FAILED — \(error.localizedDescription, privacy: .public)")
                    self.linkFailedNotice = "couldn't create your link — retry"
                }
            }
        }
        lastLinkSend = run
        run()
    }

    /// Re-run the last link send (the retry affordance on linkFailedNotice).
    func retryLinkSend() { lastLinkSend?() }

    /// [#1] Called by the View when the send animation completes (CompassView.finishSend —
    /// the single terminal funnel for all send-out onComplete closures). If the link is
    /// already built, present now; otherwise the insert-completion will present it.
    func markSendAnimationComplete() {
        sendAnimationComplete = true
        presentShareIfReady()
    }

    /// [#1] Present the share sheet only when BOTH the link is built AND the send animation
    /// has finished. Idempotent — clears the state after presenting so it fires exactly once.
    private func presentShareIfReady() {
        guard sendAnimationComplete, let text = pendingShareText else { return }
        pendingShareText = nil
        sendAnimationComplete = false
        ShareSheet.present(text)
    }

