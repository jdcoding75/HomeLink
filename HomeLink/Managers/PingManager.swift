    /// New thought arrives → catch mode. RULE: only the NEWEST incoming
    /// thought triggers the catch — anything older slips quietly into
    /// History (it's already persisted server-side in the pings table).
    func receivePing(fromName: String, emoji: String, remoteID: UUID? = nil,
                     senderStyle: String? = nil, message: String? = nil,
                     tagline: String? = nil, isTest: Bool = false,
                     autoPlay: Bool = true) {
        log.info("receivePing: from=\(fromName, privacy: .public) emoji=\(emoji, privacy: .public) remoteID=\(remoteID?.uuidString ?? "nil", privacy: .public) style=\(senderStyle ?? "nil", privacy: .public)")

        // DEDUPE: in the foreground the same thought arrives twice — once
        // over realtime (with remoteID) and once as the APNs push (without).
        // Same id, or same emoji+sender within 15 s → one catch, not two.
        // [3/6] DEV test thoughts are EXEMPT — sending the same emoji to
        // yourself twice in a row must always play, never silently de-dupe.
        let isDuplicate = !isTest && ([nowPlaying].compactMap { $0 } + queue).contains { existing in
            if let id = remoteID, existing.remoteID == id { return true }
            return existing.emoji == emoji
                && existing.fromName == fromName
                && Date.now.timeIntervalSince(existing.timestamp) < 15
        }
        if isDuplicate {
            log.info("receivePing: duplicate (realtime + push) — ignored")
            return
        }

        // QUEUE NOTIFICATION RULE: only the FIRST unread thought announces
        // itself. While one is already waiting, newcomers slip in silently —
        // no haptic, no fanfare; the badge count is the only change.
        let isFirstUnread = unreadCount == 0

        let ping = ReceivedPing(fromName: fromName, emoji: emoji, timestamp: .now,
                                remoteID: remoteID, senderStyle: senderStyle,
                                message: message, tagline: tagline, isTest: isTest)
        // MULTI-SENDER QUEUE: an active catch is NEVER interrupted, and
        // waiting thoughts are ALL kept — each with its own sender name and
        // style, so every later catch and replay is correctly attributed.
        // Oldest drops past 10 (it lives in History server-side anyway).
        var updated = queue
        updated.append(ping)
        if updated.count > Self.maxQueued {
            updated.removeFirst(updated.count - Self.maxQueued)
        }
        queue = updated
        rememberSeen(remoteID)
        AppGroupStore.pendingPingEmoji     = emoji
        AppGroupStore.pendingPingFromName  = fromName
        AppGroupStore.pendingPingTimestamp = .now
        if isFirstUnread && appState?.currentState != .sending {
            HapticEngine.thoughtArrived()   // soft directional pull, not an alert
        } else {
            log.info("receivePing: arrived silently (badge only) — first unread already waiting, or a send is in progress")
        }

        // A catch already on screen finishes its moment; anything else
        // waits on the badge and plays when the user taps for it.
        //
        // [3/6] BUG FIX — the auto-play gate used to be `queue.count == 1`,
        // so when ANY thought was already waiting in the bucket (e.g. a
        // restored offline thought, or a previous dev test), a freshly sent
        // "test thought to myself" would land silently and NEVER open the
        // receipt. The correct gate is "nothing is currently on screen": if
        // the screen is free, open the next thought. A DEV test thought is
        // always honoured immediately — it jumps the queue so the developer
        // sees the full receipt every time, even behind older waiting ones.
        // [5/5] autoPlay:false queues the thought silently for later (used by
        // "Test All Animations" so all 7 stack in the bucket, then "Auto-catch
        // all" plays them in sequence).
        if autoPlay && nowPlaying == nil {
            if appState?.currentState == .sending {
                // [2/5] SIMULTANEOUS SEND/RECEIVE — never let an arriving
                // thought interrupt a send in progress. While sending it sits
                // in the queue (badge only); the catch fires the instant the
                // send completes (the screen returns to idle and drains).
                log.info("receivePing: send in progress — queued, catch will play when the send completes")
                appState?.queueAnimation { [weak self] in self?.playNext() }
            } else if isTest, let idx = queue.firstIndex(where: { $0.id == ping.id }) {
                // DEV test thought jumps straight to the front of an idle screen.
                nowPlaying = queue.remove(at: idx)
            } else {
                // [live-arrival-fix] Start the FIRST thought whenever the screen is idle (nowPlaying == nil),
                // not only when it's the LONE queued item. A burst queues behind it; the user advances with
                // Next. While a thought rests, nowPlaying stays non-nil → new arrivals just queue.
                playNext()
            }
        }
    }

    /// Start (or skip to) the next queued thought.
    /// opened_at is set at the moment of REVEAL (markOpened), not here —
    /// "felt" means felt, not delivered.
    func playNext() {
        guard !queue.isEmpty else {
            nowPlaying = nil
            return
        }
        nowPlaying = queue.removeFirst()
    }

    /// The thought was actually experienced — bloom played, sound heard.
    func markOpened(_ ping: ReceivedPing) {
        // [2/5] Save it to local history the moment it's revealed, so the bucket
        // drawer shows it — test thoughts included (they have no server row).
        recordCaught(ping)
        if let remoteID = ping.remoteID {
            log.info("markOpened: id=\(remoteID.uuidString, privacy: .public)")
            Task { await SupabaseService.shared.markPingOpened(remoteID) }
        } else {
            // Push-delivered pings used to arrive without an id — the felt
            // receipt was silently lost. The push payload now carries pingId.
            log.warning("markOpened: no remoteID — felt receipt cannot be recorded")
        }
    }

    // [9b · B4] presenceFelt removed — its only caller was NotificationHandler's dead
    // "pointing" branch; it set the mutual-pointing state (also removed).

    // ── Replay, app-wide ─────────────────────────────────────────────────
    /// Set from any tab; RootView presents the full-screen replay overlay.
    struct ReplayItem: Identifiable, Equatable {
        let id = UUID()
        let emoji: String
        let bearingDegrees: Double
        let styleRaw: String?
        var fromName: String = ""
        // AUDIT [5/6]: the note + tagline travel with the thought; carry them
        // into replay so a replayed thought shows everything the live catch did.
        var message: String? = nil
        var tagline: String? = nil
        // [bucket delete] The caughtHistory BUCKET id (`remoteID ?? id`) this replay
        // item came from, so the overlay's Delete can remove THE RIGHT history item.
        // nil for replays that don't originate from the bucket (no Delete shown).
        var historyID: UUID? = nil
    }
    struct ReplayRequest: Identifiable, Equatable {
        let id = UUID()
        let emoji: String
        let bearingDegrees: Double
        let styleRaw: String?
        var fromName: String = ""
        var message: String? = nil
        var tagline: String? = nil
        // The full list this replay belongs to + our position, so the overlay
        // can SWIPE to the next/previous thought without re-presenting.
        var siblings: [ReplayItem] = []
        var index: Int = 0
        // [bucket delete] Bucket id for the SINGLE-item fallback (siblings empty);
        // multi-item replays carry it per-sibling on each ReplayItem instead.
        var historyID: UUID? = nil
    }
    @Published var replayRequest: ReplayRequest?

    func requestReplay(emoji: String, bearingDegrees: Double, styleRaw: String?,
                       fromName: String = "", message: String? = nil, tagline: String? = nil) {
        log.info("replay: requested — \(emoji, privacy: .public) bearing=\(Int(bearingDegrees), privacy: .public)°")
        replayRequest = ReplayRequest(emoji: emoji, bearingDegrees: bearingDegrees,
                                      styleRaw: styleRaw, fromName: fromName,
                                      message: message, tagline: tagline)
    }

    /// Replay a whole list, starting at `startIndex` — the overlay can swipe
    /// between the thoughts.
    func requestReplaySequence(_ items: [ReplayItem], startIndex: Int) {
        guard !items.isEmpty else { return }
        let i = max(0, min(items.count - 1, startIndex))
        let it = items[i]
        replayRequest = ReplayRequest(emoji: it.emoji, bearingDegrees: it.bearingDegrees,
                                      styleRaw: it.styleRaw, fromName: it.fromName,
                                      message: it.message, tagline: it.tagline,
                                      siblings: items, index: i,
                                      historyID: it.historyID)   // [bucket delete] start item's id (single-fallback)
    }

    // ── Felt receipts, live ──────────────────────────────────────────────
    /// Bumped whenever one of OUR sent pings gets opened — history views
    /// listening to this refetch and flip their dot to "felt".
    @Published var lastFeltAt: Date?

    // [9b · B4] Mutual-pointing cluster REMOVED — partnerPointingBearing, mutualMoment,
    // lastMutualMoment, and checkMutualPointing (the latter had NO live caller; the
    // RootView triggers were already commented). The source (reportPointing) was a no-op,
    // so none of this ever fired. (lastFeltAt above is the LIVE felt-receipt stream — kept.)

    /// Called when an arrival animation completes. Waiting thoughts do NOT
    /// auto-play — the badge shows the count and the user taps to catch the
    /// next when ready. (previous: auto-advance after 2 s — retired)
    func finishedPlaying(_ ping: ReceivedPing) {
        guard nowPlaying?.id == ping.id else { return }
        nowPlaying = nil
        AppGroupStore.clearPendingPing()
        // [4/5] AUTO-CATCH — when draining the bucket automatically, pause 2 s
        // then catch the next thought; stop when the bucket is empty.
        if isAutoCatching {
            if queue.isEmpty {
                isAutoCatching = false
                log.info("auto-catch: bucket drained ✓")
            } else {
                DispatchQueue.main.asyncAfter(deadline: .now() + 2.0) { [weak self] in
                    guard let self, self.isAutoCatching else { return }
                    self.playNext()
                }
            }
            return
        }
        if !queue.isEmpty {
            log.info("queue: \(self.queue.count) thought(s) waiting — badge shows, user taps to catch")
        }
    }

    /// [4/5] DEBUG auto-catch — drains the entire bucket, auto-aligning and
    /// playing each receipt in turn (ReceiptView watches `isAutoCatching` to
    /// auto-lock and auto-advance), with a 2 s pause between thoughts. The flag
    /// itself compiles in all builds but is only ever set from Developer Tools.
    @Published var isAutoCatching = false

    func startAutoCatch() {
        guard nowPlaying != nil || !queue.isEmpty else {
            log.info("auto-catch: nothing in the bucket")
            return
        }
        log.info("auto-catch: starting — \(self.queue.count + (self.nowPlaying == nil ? 0 : 1)) thought(s)")
        isAutoCatching = true
        if nowPlaying == nil { playNext() }
    }

    /// Tap-to-skip: jump straight to the next thought, no 2-second gap.
    func skip(_ ping: ReceivedPing) {
        guard nowPlaying?.id == ping.id else { return }
        nowPlaying = nil
        AppGroupStore.clearPendingPing()
        playNext()
    }

    func clearPendingPing() {
        pendingPing = nil
        AppGroupStore.clearPendingPing()
    }
}

// ── Message rules — the optional ≤30-char note that rides a thought ───────
// Pure + testable, so the same clamping/normalizing runs in the compose UI
// (CompassView) and the send path (SupabaseService.sendPing).
enum MessageRules {
    static let maxLength = 30

    /// Trim a message to the maximum length (the compose field uses this).
    static func clamped(_ message: String) -> String {
        String(message.prefix(maxLength))
    }

    /// Normalize for sending: an empty/whitespace-only message becomes nil so
    /// it's omitted from the payload entirely; otherwise it's clamped.
    static func normalized(_ message: String?) -> String? {
        guard let message else { return nil }
        let trimmed = message.trimmingCharacters(in: .whitespacesAndNewlines)
        return trimmed.isEmpty ? nil : clamped(trimmed)
    }
}
