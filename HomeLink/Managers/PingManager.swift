    private let log = Logger(subsystem: "com.jdcoding75.pointward", category: "pings")

    /// Legacy single-slot ping (still mirrored to the widget store).
    @Published var pendingPing: ReceivedPing?
    @Published var isSending   = false
    /// "Mum felt your thought ✓" — set when a sent ping gets opened remotely.
    @Published var feltNotice: String?
    /// "couldn't send — check your connection" — a real send failed after
    /// retries. The animation already played; the user must know the
    /// thought did NOT travel.
    @Published var sendFailedNotice: String?
    /// "Mum is pointing toward you 🧭" — their compass just locked onto us.
    /// (Toast retired — the ambient presence glow replaced it. Kept.)
    @Published var pointingNotice: String?

    // [9b · B4] partnerPointingAt / partnerPointingName removed with the
    // mutual-pointing cluster (set only by the deleted presenceFelt; read only by the
    // deleted CompassView edge-glow).

    // ── Thought queue ────────────────────────────────────────────────────
    /// Received thoughts waiting to be watched. Max 10; oldest drops off.
    @Published private(set) var queue: [ReceivedPing] = [] {
        didSet {
            queueCount  = queue.count + (nowPlaying == nil ? 0 : 1)
            unreadCount = queueCount
            persistQueue()
        }
    }
    /// The thought currently playing its arrival animation, if any.
    @Published var nowPlaying: ReceivedPing? {
        didSet {
            queueCount  = queue.count + (nowPlaying == nil ? 0 : 1)
            unreadCount = queueCount
        }
    }
    /// Unread thoughts (waiting + the one being caught) — drives the badge.
    @Published var queueCount: Int = 0
    /// QUEUE NOTIFICATION RULE: only the FIRST unread announces itself —
    /// arrivals while this is > 0 slip in silently (badge only). Resets
    /// to 0 automatically when the user catches up (queue drains).
    @Published private(set) var unreadCount: Int = 0

    /// [2/5] LOCAL CAUGHT HISTORY — every thought that's been caught + revealed,
    /// kept on-device so the bucket drawer shows it even when there's no server
    /// row (dev test thoughts) or the network is down. Real thoughts ALSO live
    /// server-side; the drawer dedupes by id. Newest last; capped at 50.
    @Published private(set) var caughtHistory: [ReceivedPing] = [] {
        didSet { persistCaughtHistory() }
    }

    /// [history-split 2026-06] Sent-thought history — newest last, capped 50, persisted
    /// like caughtHistory. Built only by recordSent() at the send site.
    @Published private(set) var sentHistory: [SentRecord] = [] {
        didSet { persistSentHistory() }
    }

    static let maxQueued = 50

    private let networkService: NetworkServiceProtocol

    /// State machine — wired by ServiceContainer. Catch mode and the
    /// caught-confirmation queueing rules flow through here.
    private weak var appState: AppStateManager?

    /// SENDER CAUGHT — the recipient caught our thought. The emoji we sent
    /// reappears briefly at the compass center. No text, no timestamp.
    struct CaughtMoment: Equatable {
        let emoji: String
        let at:    Date
    }
    @Published var caughtMoment: CaughtMoment?

    struct ReceivedPing: Equatable, Identifiable {
        let id = UUID()
        let fromName:  String
        let emoji:     String
        let timestamp: Date
        var remoteID:  UUID? = nil      // Supabase ping id, for read receipts
        /// sender_style from the wire — the SENDER's animation personality.
        /// nil (pre-migration rows) falls back to glow at the call site.
        var senderStyle: String? = nil
        /// [5/5] Optional short message (≤30 chars) the sender attached.
        var message: String? = nil
        /// The sender's per-person tagline, travelling with the thought.
        var tagline: String? = nil
        /// [2/5] DEBUG: marks a thought generated by the developer test tools
        /// so "clear test thoughts" can remove only these, never real ones.
        var isTest: Bool = false
    }

    /// [history-split 2026-06] A thought the USER sent — the sent-side mirror of
    /// ReceivedPing, for the "thoughts sent ✦" bucket section. Display-only (no
    /// remoteID/read-receipt, no isTest: the demo path never records a sent thought).
    struct SentRecord: Equatable, Identifiable {
        let id = UUID()
        let toName:      String
        let emoji:       String
        let timestamp:   Date
        var senderStyle: String? = nil
        var message:     String? = nil
        var tagline:     String? = nil
    }

    init(networkService: NetworkServiceProtocol, appState: AppStateManager? = nil) {
        self.networkService = networkService
        self.appState = appState
        restoreQueue()          // waiting thoughts survive an app relaunch
        restoreCaughtHistory()  // [2/5] caught-thought history survives too
        restoreSentHistory()    // [history-split 2026-06] sent-thought history survives too
    }

    static let maxCaughtHistory = 50

    /// [2/5] Record a thought as caught + revealed so it appears in the bucket
    /// drawer — works for real AND dev test thoughts, the latter having no
    /// server row. Idempotent by id (a re-reveal never duplicates).
    func recordCaught(_ ping: ReceivedPing) {
        if let id = ping.remoteID, caughtHistory.contains(where: { $0.remoteID == id }) { return }
        if caughtHistory.contains(where: { $0.id == ping.id }) { return }
        var updated = caughtHistory
        updated.append(ping)
        if updated.count > Self.maxCaughtHistory {
            updated.removeFirst(updated.count - Self.maxCaughtHistory)
        }
        caughtHistory = updated
        log.info("history: recorded caught thought from \(ping.fromName, privacy: .public) (\(self.caughtHistory.count) kept)")
    }

    /// [history-split 2026-06] Append a sent thought (newest last; cap maxCaughtHistory).
    /// No id/remoteID dedup — every send is a distinct event.
    func recordSent(_ record: SentRecord) {
        var updated = sentHistory
        updated.append(record)
        if updated.count > Self.maxCaughtHistory {
            updated.removeFirst(updated.count - Self.maxCaughtHistory)
        }
        sentHistory = updated
        log.info("history: recorded sent thought to \(record.toName, privacy: .public) (\(self.sentHistory.count) kept)")
    }

    /// [bucket delete · ⭐ Phase-3 backbone] Remove ONE thought from local history by its
    /// BUCKET id — the value the bucket/replay carries, which is `remoteID ?? id` (matches
    /// how `loadCompassThoughts` keys each PingRecord). Idempotent: a no-op if absent.
    /// `caughtHistory`'s didSet re-persists automatically (current UserDefaults shape;
    /// NO schema/preserved-flag change). This is the SINGLE per-item remove for
    /// caughtHistory — the future History-tab swipe-delete reuses it.
    func removeFromHistory(id: UUID) {
        let before = caughtHistory.count
        caughtHistory.removeAll { ($0.remoteID ?? $0.id) == id }
        if caughtHistory.count != before {
            log.info("history: removed 1 thought (\(self.caughtHistory.count) kept)")
        }
    }

    private func persistCaughtHistory() {
        let stored = caughtHistory.map {
            PersistedPing(fromName: $0.fromName, emoji: $0.emoji,
                          timestamp: $0.timestamp, remoteID: $0.remoteID,
                          senderStyle: $0.senderStyle, message: $0.message,
                          tagline: $0.tagline, isTest: $0.isTest)
        }
        if let data = try? JSONEncoder().encode(stored) {
            UserDefaults.standard.set(data, forKey: "caughtHistory")
        }
    }

    private func restoreCaughtHistory() {
        guard let data = UserDefaults.standard.data(forKey: "caughtHistory"),
              let stored = try? JSONDecoder().decode([PersistedPing].self, from: data),
              !stored.isEmpty else { return }
        caughtHistory = stored.map {
            ReceivedPing(fromName: $0.fromName, emoji: $0.emoji,
                         timestamp: $0.timestamp, remoteID: $0.remoteID,
                         senderStyle: $0.senderStyle, message: $0.message,
                         tagline: $0.tagline, isTest: $0.isTest)
        }
    }

    // ── [history-split 2026-06] Sent-thought persistence (new "sentHistory" key) ──
    private struct PersistedSent: Codable {
        let toName: String
        let emoji: String
        let timestamp: Date
        var senderStyle: String? = nil
        var message: String? = nil
        var tagline: String? = nil
    }

    private func persistSentHistory() {
        let stored = sentHistory.map {
            PersistedSent(toName: $0.toName, emoji: $0.emoji, timestamp: $0.timestamp,
                          senderStyle: $0.senderStyle, message: $0.message, tagline: $0.tagline)
        }
        if let data = try? JSONEncoder().encode(stored) {
            UserDefaults.standard.set(data, forKey: "sentHistory")
        }
    }

    private func restoreSentHistory() {
        guard let data = UserDefaults.standard.data(forKey: "sentHistory"),
              let stored = try? JSONDecoder().decode([PersistedSent].self, from: data),
              !stored.isEmpty else { return }
        sentHistory = stored.map {
            SentRecord(toName: $0.toName, emoji: $0.emoji, timestamp: $0.timestamp,
                       senderStyle: $0.senderStyle, message: $0.message, tagline: $0.tagline)
        }
    }

    // ── Queue persistence — unread thoughts survive relaunches ──────────

    private struct PersistedPing: Codable {
        let fromName: String
        let emoji: String
        let timestamp: Date
        let remoteID: UUID?
        let senderStyle: String?
        var message: String? = nil
        var tagline: String? = nil
        var isTest: Bool = false
    }

    private func persistQueue() {
        let stored = queue.map {
            PersistedPing(fromName: $0.fromName, emoji: $0.emoji,
                          timestamp: $0.timestamp, remoteID: $0.remoteID,
                          senderStyle: $0.senderStyle, message: $0.message,
                          tagline: $0.tagline, isTest: $0.isTest)
        }
        if let data = try? JSONEncoder().encode(stored) {
            UserDefaults.standard.set(data, forKey: "pendingThoughtQueue")
        }
    }

    private func restoreQueue() {
        guard let data = UserDefaults.standard.data(forKey: "pendingThoughtQueue"),
              let stored = try? JSONDecoder().decode([PersistedPing].self, from: data),
              !stored.isEmpty else { return }
        log.info("queue: restored \(stored.count) waiting thought(s) from last session")
        queue = stored.map {
            ReceivedPing(fromName: $0.fromName, emoji: $0.emoji,
                         timestamp: $0.timestamp, remoteID: $0.remoteID,
                         senderStyle: $0.senderStyle, message: $0.message,
                         tagline: $0.tagline, isTest: $0.isTest)
        }
    }

